//
// Tegezés throughout, which is what a messenger between friends speaks. No
// grammatical gender anywhere, because Hungarian has none to guess at.
//
// Hungarian puts the noun in the singular after a numeral — 3 üzenet, not
// 3 üzenetek — so every plural key carries the same form in all four
// categories. That is the language working, not four lines somebody forgot.
//
// Names are never given a case ending: a suffix has to agree with the vowels
// of the word it lands on, and `{name}` is whatever somebody typed. Sentences
// around a name are built with a colon instead.

